/* Knowledge Assistant — retrieval-first, works with zero backend.
   Loads a precomputed chunk index (docs-site/content/assets/embeddings/index.json,
   generated by scripts/build-search-index.js), scores chunks against the
   user's question with simple term-frequency overlap, and shows the best
   matches with links back to the source lesson. If the user pastes their own
   Anthropic API key, it also asks Claude to synthesize a short cited answer
   from the retrieved passages — called directly from the browser, so the key
   never touches any server this site controls. */

(function () {
  let INDEX = null;

  function siteRoot() {
    // Works whether the site is served at the domain root or a subpath.
    const base = document.querySelector('link[rel="canonical"]');
    return "";
  }

  async function loadIndex() {
    if (INDEX) return INDEX;
    const res = await fetch("/assets/embeddings/index.json");
    INDEX = await res.json();
    return INDEX;
  }

  const LOWER_PRIORITY_SECTIONS = new Set(["practice questions", "scenario questions"]);
  const NAV_PAGES = new Set(["index.md", "fps/index.md", "cpcm/index.md"]);

  function score(chunk, terms) {
    const hay = (chunk.title + " " + chunk.section + " " + chunk.text).toLowerCase();
    let raw = 0;
    let covered = 0;
    terms.forEach((t) => {
      if (!t) return;
      const count = hay.split(t).length - 1;
      if (count > 0) covered++;
      raw += count;
      if (chunk.title.toLowerCase().includes(t)) raw += 3;
      if (chunk.section.toLowerCase().includes(t)) raw += 2;
    });
    // Reward passages that cover more of the distinct query terms, not just
    // ones that repeat a single common word many times.
    let s = raw * (1 + covered / terms.length);
    if (LOWER_PRIORITY_SECTIONS.has(chunk.section.toLowerCase())) s *= 0.4;
    if (NAV_PAGES.has(chunk.page)) s *= 0.3; // navigation/landing tables, not lesson substance
    return s;
  }

  function retrieve(question, k) {
    const terms = question.toLowerCase().match(/[a-z0-9]+/g) || [];
    const stop = new Set(["what", "is", "the", "a", "an", "of", "in", "to", "and", "or", "how", "does", "do", "explain", "compare", "for", "with", "on"]);
    const meaningful = terms.filter((t) => !stop.has(t) && t.length > 1);
    const useTerms = meaningful.length ? meaningful : terms;
    return INDEX
      .map((c) => ({ c, s: score(c, useTerms) }))
      .filter((x) => x.s > 0)
      .sort((a, b) => b.s - a.s)
      .slice(0, k)
      .map((x) => x.c);
  }

  function renderHits(hits) {
    const el = document.getElementById("assistant-results");
    if (!hits.length) {
      el.innerHTML = `<p>No matching passages found. Try different wording, or browse the <a href="/glossary/">glossary</a>.</p>`;
      return;
    }
    el.innerHTML = hits
      .map(
        (h) => `<div class="assistant-hit">
          <div><strong><a href="${h.url}">${h.title}</a></strong> &middot; ${h.section}</div>
          <div>${h.text.slice(0, 320)}${h.text.length > 320 ? "…" : ""}</div>
        </div>`
      )
      .join("");
  }

  async function synthesize(question, hits, apiKey) {
    const status = document.getElementById("assistant-status");
    status.textContent = "Asking Claude to summarise the retrieved passages…";
    const context = hits
      .map((h, i) => `[${i + 1}] ${h.title} — ${h.section}\n${h.text}`)
      .join("\n\n");
    const prompt = `Answer the question using ONLY the numbered source passages below. Cite sources inline like [1]. If the passages don't contain the answer, say so.\n\nQuestion: ${question}\n\nSources:\n${context}`;

    try {
      const res = await fetch("https://api.anthropic.com/v1/messages", {
        method: "POST",
        headers: {
          "content-type": "application/json",
          "x-api-key": apiKey,
          "anthropic-version": "2023-06-01",
          "anthropic-dangerous-direct-browser-access": "true",
        },
        body: JSON.stringify({
          model: "claude-haiku-4-5-20251001",
          max_tokens: 500,
          messages: [{ role: "user", content: prompt }],
        }),
      });
      if (!res.ok) {
        const errText = await res.text();
        status.textContent = "Claude API error (" + res.status + ") — showing retrieved passages only.";
        console.error(errText);
        return;
      }
      const data = await res.json();
      const text = (data.content || []).map((b) => b.text || "").join("");
      const el = document.getElementById("assistant-results");
      el.insertAdjacentHTML(
        "afterbegin",
        `<div class="assistant-hit" style="border-left-color:#0f7a41;"><strong>Synthesized answer</strong><div style="margin-top:6px; white-space:pre-wrap;">${text.replace(/</g, "&lt;")}</div></div>`
      );
      status.textContent = "";
    } catch (e) {
      status.textContent = "Could not reach the Anthropic API from this browser (network/CORS) — showing retrieved passages only.";
      console.error(e);
    }
  }

  async function ask() {
    const question = document.getElementById("assistant-question").value.trim();
    const apiKey = document.getElementById("assistant-api-key").value.trim();
    const status = document.getElementById("assistant-status");
    if (!question) return;

    status.textContent = "Searching the knowledge base…";
    await loadIndex();
    const hits = retrieve(question, 5);
    renderHits(hits);
    status.textContent = hits.length ? "" : "";

    if (apiKey && hits.length) {
      await synthesize(question, hits, apiKey);
    }
  }

  document.addEventListener("DOMContentLoaded", () => {
    const btn = document.getElementById("assistant-ask");
    if (!btn) return; // not on the assistant page
    btn.addEventListener("click", ask);
    document.getElementById("assistant-question").addEventListener("keydown", (e) => {
      if (e.key === "Enter" && (e.metaKey || e.ctrlKey)) ask();
    });
  });
})();
